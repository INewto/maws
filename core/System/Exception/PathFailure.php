<?php

namespace Maws\System\Exception;

/**
 * Путь вышел за свой корень: «..» некуда схлопывать. Это не сбой машины и не ошибка в коде, а
 * негодный вход — поэтому 400, а не 500.
 *
 * Своя копия, отдельная от одноимённой у хелпера: ядру нужен отказ при разборе пути, а хелпер
 * обязан удаляться, не роняя ядро. Две реализации здесь — не недосмотр, у них разные сроки жизни.
 */
class PathFailure extends MawsException
{
    public function __construct(string $path)
    {
        parent::__construct("путь выходит за свой корень: {$path} — «..» некуда схлопывать");
    }

    public function status(): int
    {
        return 400;
    }
}
