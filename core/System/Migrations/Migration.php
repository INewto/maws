<?php

namespace Maws\System\Migrations;

use Maws\System\Contract\Purpose;
use Maws\System\Contract\Returns;

/**
 * Миграция — это файл в db/migrations, который возвращает наследника этого класса.
 *
 * У миграции две двери: up() и down(). Откат пишет автор: только он знает, что делать
 * с тем, чего в снимке схемы нет, — с последовательностями, представлениями, триггерами
 * и строками, изменёнными UPDATE. Полностью отследить изменения миграции нельзя, поэтому
 * попытка вывести откат из разницы снимков упёрлась бы в «а это вернуть нечем».
 *
 * Снимок при этом не выброшен: Migrator сверяет с ним результат down(). Не сошлось —
 * откат отменяется транзакцией, база остаётся как была. down() — обещание, но
 * невыполненное обещание видно сразу, а не через полгода.
 */
abstract class Migration
{
    /**
     * Операторы миграции по порядку. Сначала создаются таблицы, потом в них пишутся
     * данные — это обычный SQL, и он идёт одной транзакцией вместе с записью в журнал.
     */
    #[Purpose('Возвращает операторы, которые переводят базу в состояние после миграции.')]
    #[Returns('array', 'список SQL-операторов в порядке выполнения')]
    abstract public function up(): array;

    /**
     * Операторы отката — в порядке, обратном up(). Пустой список — законный ответ
     * «откатывать нечего»: тогда make rollback откажется, потому что структура
     * не вернётся к снимку «до». Данные откат не сверяет — их знает только автор.
     */
    #[Purpose('Возвращает операторы, которые возвращают базу к состоянию до миграции.')]
    #[Returns('array', 'список SQL-операторов в порядке выполнения')]
    abstract public function down(): array;
}
